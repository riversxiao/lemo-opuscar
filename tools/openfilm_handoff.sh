#!/usr/bin/env bash
# Package a finished lemo MP4 as a minimal OpenFilm project (single video clip).
# Spec: https://openfilm.dev/docs/manual/  — film.html cuts media with <video>/<audio>.
# This is a handoff stub, not a full frame(t) port of the lemo engine.
set -euo pipefail

usage() {
  echo "usage: sh tools/openfilm_handoff.sh <film_dir> [out_name]" >&2
  echo "  film_dir: lemo project containing a muxed .mp4 (out/*.mp4 or *.mp4)" >&2
  echo "  writes <film_dir>/openfilm-handoff/{film.html,assets/master.mp4,README.md}" >&2
  exit 2
}

[[ $# -ge 1 ]] || usage
FILM_DIR=$(cd "$1" && pwd)
NAME=${2:-$(basename "$FILM_DIR")}
OUT="$FILM_DIR/openfilm-handoff"

MP4=""
for cand in "$FILM_DIR/out/final.mp4" "$FILM_DIR/out/"*.mp4 "$FILM_DIR/"*.mp4; do
  # shellcheck disable=SC2086
  for f in $cand; do
    [[ -f "$f" ]] || continue
    MP4=$f
    break 2
  done
done
if [[ -z "$MP4" ]]; then
  echo "openfilm_handoff: no .mp4 found under $FILM_DIR (looked for out/final.mp4, out/*.mp4, *.mp4)" >&2
  exit 1
fi

DUR=""
if command -v ffprobe >/dev/null 2>&1; then
  DUR=$(ffprobe -v error -show_entries format=duration -of default=nk=1:nw=1 "$MP4" 2>/dev/null || true)
fi
DUR=${DUR:-30}
# trim to 3 decimal places without requiring bc
DUR=$(awk -v d="$DUR" 'BEGIN{printf "%.3f", d+0}')

mkdir -p "$OUT/assets"
cp -f "$MP4" "$OUT/assets/master.mp4"

# Optional stems if present (separate tracks for NLE polish)
STEM_HTML=""
if [[ -f "$FILM_DIR/audio/vo.wav" ]]; then
  cp -f "$FILM_DIR/audio/vo.wav" "$OUT/assets/vo.wav"
  STEM_HTML+=$'  <audio src="assets/vo.wav" volume="1"></audio>\n'
fi
if [[ -f "$FILM_DIR/audio/music.wav" ]]; then
  cp -f "$FILM_DIR/audio/music.wav" "$OUT/assets/music.wav"
  STEM_HTML+=$'  <audio src="assets/music.wav" volume="0.35"></audio>\n'
elif [[ -f "$FILM_DIR/audio/bed.wav" ]]; then
  cp -f "$FILM_DIR/audio/bed.wav" "$OUT/assets/music.wav"
  STEM_HTML+=$'  <audio src="assets/music.wav" volume="0.35"></audio>\n'
fi

cat > "$OUT/film.html" << HTML
<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=1920, height=1080">
<title>${NAME} · lemo → OpenFilm handoff</title>
</head>
<body>
<!-- Single-clip handoff from lemo-opuscar. Not a shot-level frame(t) port.
     Open in Studio, then export timeline for Premiere / Resolve / FCP. -->
<section>
  <video src="assets/master.mp4#t=0,${DUR}" at="0" style="left:0;top:0;width:1920px;height:1080px"></video>
</section>
<section>
${STEM_HTML}</section>
</body>
</html>
HTML

cat > "$OUT/README.md" << MD
# OpenFilm handoff · ${NAME}

Generated by \`tools/openfilm_handoff.sh\` from lemo project:

- source mp4: \`${MP4}\`
- duration (ffprobe or fallback): ${DUR}s

## Open

\`\`\`sh
cd "$(basename "$OUT")"   # or: cd $OUT
npx -y openfilm@latest open .
\`\`\`

Needs Node 22.2+ and ffmpeg. In Studio: edit / trim, then **export timeline** for Premiere, DaVinci Resolve, or Final Cut Pro.

## Limits

- One picture track = the finished lemo mux (not per-shot HTML pages).
- Stem audio tracks are copied only when \`audio/vo.wav\` / \`audio/music.wav|bed.wav\` exist; levels are guesses — remix in the NLE.
- Full lemo → multi-page OpenFilm adapter is **not** implemented; see \`plugin/skills/lemo-export-nle/SKILL.md\`.
MD

echo "openfilm_handoff: wrote $OUT"
echo "  mp4: $MP4"
echo "  duration: ${DUR}s"
echo "  next: cd $OUT && npx -y openfilm@latest open ."
