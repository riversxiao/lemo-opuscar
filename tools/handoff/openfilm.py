"""OpenFilm handoff: multi-shot film.html + EDL + ffmpeg rebuild from a finished lemo mux."""
from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from .common import (
    copy_stem_audio,
    find_master_mp4,
    html_escape,
    load_shots,
    probe_duration,
    write_cmx3600_edl,
    write_ffmpeg_concat,
)


def _video_clips_html(shots: list[dict[str, Any]], dur: float) -> str:
    if not shots:
        return (
            f'  <video src="assets/master.mp4#t=0,{dur:.3f}" at="0" '
            f'style="left:0;top:0;width:1920px;height:1080px"></video>\n'
        )
    parts = []
    for sh in shots:
        t0, t1 = sh["t0"], sh["t1"]
        if t1 <= t0:
            continue
        parts.append(
            f'  <video id="{html_escape(sh["id"])}" '
            f'src="assets/master.mp4#t={t0:.3f},{t1:.3f}" at="{t0:.3f}" '
            f'style="left:0;top:0;width:1920px;height:1080px"></video>'
        )
    return "\n".join(parts) + "\n"


def _audio_section_html(stems: dict[str, str]) -> str:
    """Stems are copied under assets/ for NLE remix but NOT placed as <audio>
    clips by default — each picture <video> already carries the mixed soundtrack.
    Uncomment in Studio / edit film.html if you want isolated stems.
    """
    if not stems:
        return "  <!-- no stem WAVs found -->\n"
    notes = ", ".join(f"{k}={v}" for k, v in stems.items())
    return (
        f"  <!-- stems on disk (not auto-played; avoids doubling mux audio): {notes} -->\n"
    )


def export_openfilm(
    film_dir: Path,
    *,
    name: str | None = None,
    out_dir: Path | None = None,
    extract_shots: bool = False,
) -> dict[str, Any]:
    film_dir = film_dir.resolve()
    name = name or film_dir.name
    out = (out_dir or (film_dir / "openfilm-handoff")).resolve()
    if out.exists():
        shutil.rmtree(out)
    assets = out / "assets"
    assets.mkdir(parents=True)

    mp4 = find_master_mp4(film_dir)
    dur = probe_duration(mp4)
    shots, shot_src, dur_hint = load_shots(film_dir)
    if dur_hint and abs(dur_hint - dur) < 0.05:
        pass
    elif dur_hint and not shots:
        dur = float(dur_hint)

    if not shots:
        shots = [
            {
                "id": "master",
                "t0": 0.0,
                "t1": round(dur, 6),
                "dur": round(dur, 6),
                "text": name,
                "role": "full",
                "voIds": [],
            }
        ]
        shot_src = "fallback-full"

    shutil.copy2(mp4, assets / "master.mp4")
    stems = copy_stem_audio(film_dir, assets)

    safe_name = html_escape(name)
    film_html = f"""<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=1920, height=1080">
<title>{safe_name} · lemo → OpenFilm handoff</title>
</head>
<body>
<!-- Multi-shot handoff from lemo-opuscar. Picture = trims of the finished mux
     (not a frame(t) port of the lemo engine). Edit / reorder in Studio, then
     export timeline for Premiere / Resolve / FCP. -->
<section>
{_video_clips_html(shots, dur)}</section>
<section>
{_audio_section_html(stems)}</section>
</body>
</html>
"""
    (out / "film.html").write_text(film_html, encoding="utf-8")

    write_cmx3600_edl(out / "timeline.edl", title=name, shots=shots, fps=24)
    write_ffmpeg_concat(out / "rebuild_shots.sh", shots)

    manifest = {
        "kind": "lemo-openfilm-handoff",
        "version": 2,
        "name": name,
        "sourceFilm": str(film_dir),
        "sourceMp4": str(mp4),
        "durationSec": round(dur, 3),
        "shotSource": shot_src,
        "shotCount": len(shots),
        "shots": shots,
        "stems": stems,
        "artifacts": {
            "filmHtml": "film.html",
            "master": "assets/master.mp4",
            "edl": "timeline.edl",
            "ffmpegConcat": "ffmpeg_concat.txt",
            "rebuild": "rebuild_shots.sh",
        },
        "limits": [
            "Picture track is trims of the finished mux, not per-shot HTML pages / frame(t).",
            "Stem audio is optional; master.mp4 already contains the mix — mute stems in Studio if doubling.",
            "OpenFilm Studio GUI needs a one-time browser download (`npx openfilm open`).",
            "CMX3600 EDL is picture-only; verify reel path in your NLE.",
        ],
    }
    (out / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    readme = f"""# OpenFilm handoff · {name}

Generated by `tools/openfilm_handoff.sh` (v2 multi-shot) from lemo project.

- source mp4: `{mp4}`
- duration (ffprobe): {dur:.3f}s
- shots: **{len(shots)}** from `{shot_src}`

## Layout

| path | what |
|---|---|
| `film.html` | OpenFilm project — one `<video>` clip per shot (`#t=in,out` + `at`) |
| `assets/master.mp4` | finished lemo mux |
| `timeline.edl` | CMX3600-style EDL (picture events) |
| `ffmpeg_concat.txt` + `rebuild_shots.sh` | extract shot clips + concat rebuild |
| `manifest.json` | machine-readable index |

## Open in OpenFilm

```sh
cd openfilm-handoff
npx -y openfilm@latest look          # contact sheet (downloads browser once)
npx -y openfilm@latest open .        # Studio (GUI; needs display / browser)
```

Needs Node 22+ and ffmpeg. `look` was verified on this fork's box; Studio `open`
downloads ~100MB Chromium the first time.

## Offline rebuild (no OpenFilm)

```sh
bash rebuild_shots.sh    # writes shots/*.mp4 + rebuilt_picture.mp4
```

## Limits

- Not a shot-level `frame(t)` port of the lemo engine.
- Stem WAVs copied when present (`voices/*.wav`, `music/bed.wav`, `mix.wav`).
- Full Premiere/Resolve XML is still TODO; use Studio export or the EDL + master.
"""
    (out / "README.md").write_text(readme, encoding="utf-8")

    extracted = 0
    if extract_shots:
        import subprocess

        shots_dir = out / "shots"
        shots_dir.mkdir(exist_ok=True)
        for i, sh in enumerate(shots):
            dest = shots_dir / f"{i:02d}_{sh['id']}.mp4"
            cmd = [
                "ffmpeg",
                "-y",
                "-hide_banner",
                "-loglevel",
                "error",
                "-ss",
                str(sh["t0"]),
                "-to",
                str(sh["t1"]),
                "-i",
                str(assets / "master.mp4"),
                "-an",
                "-c:v",
                "libx264",
                "-preset",
                "veryfast",
                "-crf",
                "18",
                "-pix_fmt",
                "yuv420p",
                str(dest),
            ]
            subprocess.check_call(cmd)
            extracted += 1
        manifest["extractedShots"] = extracted
        (out / "manifest.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )

    return {
        "out": str(out),
        "mp4": str(mp4),
        "durationSec": round(dur, 3),
        "shotCount": len(shots),
        "shotSource": shot_src,
        "extractedShots": extracted,
        "manifest": str(out / "manifest.json"),
    }
